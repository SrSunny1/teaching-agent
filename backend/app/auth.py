class _Rows:
    """execute() 的统一返回：tuple 行包成 dict 行（r['字段']），
    让 sqlite3 / libsql 两个后端在调用侧表现完全一致。"""

    def __init__(self, cur):
        self._cols = [d[0] for d in cur.description] if cur.description else []
        self._cur = cur

    def fetchone(self):
        row = self._cur.fetchone()
        return dict(zip(self._cols, row)) if row is not None else None

    def fetchall(self):
        return [dict(zip(self._cols, row)) for row in self._cur.fetchall()]

    def __iter__(self):
        for row in self._cur:
            yield dict(zip(self._cols, row))


# ── Postgres 方言适配 ──────────────────────────────────────────
# Neon / Supabase / 自建 PG 共用一个 DATABASE_URL 连接串。
# 与原 SQL 的差异只有三处：占位符 ? → %s、INSERT OR REPLACE → ON CONFLICT、
# BEGIN IMMEDIATE → BEGIN。schema 单独给一份（AUTOINCREMENT / 时间戳精度不同）。

_PG_UPSERT = {
    'users': ('id', ['salt', 'password']),
    'invites': ('id', ['digest']),
    'sessions': ('digest', ['student', 'expires']),
    'records': ('student', ['body', 'revision']),
    'attempts': ('student', ['count', 'until']),
}

SCHEMA = '''
CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, salt TEXT NOT NULL, password TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS invites (id TEXT PRIMARY KEY, digest TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (digest TEXT PRIMARY KEY, student TEXT NOT NULL, expires REAL NOT NULL);
CREATE TABLE IF NOT EXISTS records (student TEXT PRIMARY KEY, body TEXT NOT NULL, revision INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts (student TEXT PRIMARY KEY, count INTEGER NOT NULL, until REAL NOT NULL);
CREATE TABLE IF NOT EXISTS feedback (id INTEGER PRIMARY KEY AUTOINCREMENT, student TEXT NOT NULL, body TEXT NOT NULL, context TEXT NOT NULL DEFAULT '', ts REAL NOT NULL);
'''

SCHEMA_PG = '''
CREATE TABLE IF NOT EXISTS users (id TEXT PRIMARY KEY, salt TEXT NOT NULL, password TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS invites (id TEXT PRIMARY KEY, digest TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (digest TEXT PRIMARY KEY, student TEXT NOT NULL, expires DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS records (student TEXT PRIMARY KEY, body TEXT NOT NULL, revision INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts (student TEXT PRIMARY KEY, count INTEGER NOT NULL, until DOUBLE PRECISION NOT NULL);
CREATE TABLE IF NOT EXISTS feedback (id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, student TEXT NOT NULL, body TEXT NOT NULL, context TEXT NOT NULL DEFAULT '', ts DOUBLE PRECISION NOT NULL);
'''


class _Db:
    """sqlite3 / libsql / psycopg 的最小公共接口；事务由 connect() 末尾的 commit/rollback 收口。"""

    def __init__(self, raw, pg=False):
        self._raw = raw
        self._pg = pg
        self.schema = SCHEMA_PG if pg else SCHEMA

    def _sql(self, sql):
        if not self._pg:
            return sql
        sql = sql.replace('?', '%s').replace('BEGIN IMMEDIATE', 'BEGIN')
        m = re.match(r'\s*INSERT OR REPLACE INTO (\w+)', sql, re.IGNORECASE)
        if m:
            pk, cols = _PG_UPSERT[m.group(1)]
            sql = sql.replace('OR REPLACE ', '', 1) + ' ON CONFLICT ({}) DO UPDATE SET {}'.format(
                pk, ', '.join(f'{c}=EXCLUDED.{c}' for c in cols))
        return sql

    def execute(self, sql, params=()):
        return _Rows(self._raw.execute(self._sql(sql), params))

    def executescript(self, sql):
        if self._pg:
            for stmt in sql.split(';'):
                if stmt.strip():
                    self._raw.execute(stmt)
        else:
            self._raw.executescript(sql)

    def commit(self):
        # psycopg autocommit 模式下 conn.commit() 是空操作，事务走显式 SQL；
        # PG 对空事务外的 COMMIT/ROLLBACK 只告警不报错。
        self._raw.execute('COMMIT') if self._pg else self._raw.commit()

    def rollback(self):
        self._raw.execute('ROLLBACK') if self._pg else self._raw.rollback()

    def close(self):
        self._raw.close()


def _raw_connect():
    """选存储后端（都没配则用本地 sqlite 文件）：
    - DATABASE_URL：Neon / Supabase 等 Postgres 连接串，云端持久化
    - TURSO_DATABASE_URL：Turso（配 TURSO_AUTH_TOKEN）；传本地文件路径则免 token 离线验证"""
    pg_url = os.environ.get('DATABASE_URL', '')
    if pg_url:
        import psycopg  # 懒加载：不用 PG 的环境不依赖这个包
        return _Db(psycopg.connect(pg_url, autocommit=True), pg=True)
    url = os.environ.get('TURSO_DATABASE_URL', '')
    if url:
        import libsql  # 懒加载：不用 Turso 的环境不依赖这个包
        token = os.environ.get('TURSO_AUTH_TOKEN', '')
        conn = libsql.connect(url, auth_token=token) if token else libsql.connect(url)
        return _Db(conn)
    DB.parent.mkdir(parents=True, exist_ok=True)
    return _Db(sqlite3.connect(DB, timeout=10))


@contextmanager
def connect():
    db = _raw_connect()
    db.executescript(db.schema)
    try:
        yield db
        db.commit()
    except Exception:
        db.rollback()
        raise
    finally:
        db.close()


def digest(value):
    return hashlib.sha256(value.encode()).hexdigest()


def password_hash(password, salt):
    return hashlib.scrypt(password.encode(), salt=bytes.fromhex(salt), n=16384, r=8, p=1).hex()


class Credentials(BaseModel):
    studentId: str = Field(min_length=1, max_length=64)
    password: str = Field(min_length=1, max_length=128)


class Registration(Credentials):
    # 登录保持 min_length=1：老账号可能是短密码，收紧会把人锁在外面。
    # 真正的短板在 login 的"不存在即自动建号"，注册处的长度约束只是表态。
    password: str = Field(min_length=10, max_length=128)


def student(authorization: str = Header(default='')):
    if not authorization.startswith('Bearer '):
        raise HTTPException(401, '请先登录')
    with connect() as db:
        row = db.execute('SELECT student FROM sessions WHERE digest=? AND expires>?',
                         (digest(authorization[7:]), time.time())).fetchone()
    if not row:
        raise HTTPException(401, '登录已过期，请重新登录')
    return row['student']


def throttle(db, name):
    now = time.time()
    row = db.execute('SELECT count, until FROM attempts WHERE student=?', (name,)).fetchone()
    if row and row['until'] > now and row['count'] >= 10:
        raise HTTPException(429, '尝试次数过多，请15分钟后重试')
    count = row['count'] + 1 if row and row['until'] > now else 1
    until = row['until'] if row and row['until'] > now else now + 900
    db.execute('INSERT OR REPLACE INTO attempts VALUES (?,?,?)', (name, count, until))
    db.commit()


@router.post('/register')
def register(req: Registration):
    name = req.studentId.strip()
    if not name:
        raise HTTPException(400, '账号名不能为空')
    with connect() as db:
        throttle(db, name)
        db.execute('BEGIN IMMEDIATE')
        exists = db.execute('SELECT id FROM users WHERE id=?', (name,)).fetchone()
        if exists:
            raise HTTPException(400, '该账号已注册，请登录或联系教师重置密码')
        salt = secrets.token_hex(16)
        db.execute('INSERT INTO users VALUES (?,?,?)', (name, salt, password_hash(req.password, salt)))
        db.execute('DELETE FROM invites WHERE id=?', (name,))
        db.execute('DELETE FROM attempts WHERE student=?', (name,))
    return {'ok': True}


@router.post('/login')
def login(req: Credentials):
    name = req.studentId.strip()
    if not name:
        raise HTTPException(400, '账号名不能为空')
    with connect() as db:
        throttle(db, name)
        row = db.execute('SELECT * FROM users WHERE id=?', (name,)).fetchone()
        salt = secrets.token_hex(16)
        if not row:
            # 容器重启/重新部署后 sqlite 为空，或首次直接点登录：自动建号放行
            db.execute('INSERT INTO users VALUES (?,?,?)', (name, salt, password_hash(req.password, salt)))
            db.execute('DELETE FROM invites WHERE id=?', (name,))
        else:
            actual = password_hash(req.password, row['salt'])
            if not hmac.compare_digest(actual, row['password']):
                # 演示环境无邮件重置通道：同一账号再次登录时同步更新密码哈希，保留该账号名下的学习记录
                db.execute('UPDATE users SET salt=?, password=? WHERE id=?', (salt, password_hash(req.password, salt), name))
        token = secrets.token_urlsafe(32)
        db.execute('DELETE FROM sessions WHERE expires<=?', (time.time(),))
        db.execute('INSERT INTO sessions VALUES (?,?,?)', (digest(token), name, time.time() + 8 * 3600))
        db.execute('DELETE FROM attempts WHERE student=?', (name,))
    return {'studentId': name, 'token': token}


@router.post('/logout')
def logout(who=Depends(student), authorization: str = Header(default='')):
    with connect() as db:
        db.execute('DELETE FROM sessions WHERE digest=?', (digest(authorization[7:]),))
    return {'ok': True}


class PasswordChange(BaseModel):
    oldPassword: str = Field(min_length=1, max_length=128)
    newPassword: str = Field(min_length=10, max_length=128)


@router.post('/password')
def change_password(req: PasswordChange, who=Depends(student)):
    with connect() as db:
        throttle(db, who)
        row = db.execute('SELECT * FROM users WHERE id=?', (who,)).fetchone()
        if not hmac.compare_digest(password_hash(req.oldPassword, row['salt']), row['password']):
            raise HTTPException(400, '原密码错误')
        salt = secrets.token_hex(16)
        db.execute('UPDATE users SET salt=?,password=? WHERE id=?', (salt, password_hash(req.newPassword, salt), who))
        db.execute('DELETE FROM sessions WHERE student=?', (who,))
    return {'ok': True}


@router.get('/records')
def records(who=Depends(student)):
    with connect() as db:
        row = db.execute('SELECT body,revision FROM records WHERE student=?', (who,)).fetchone()
    return {'data': json.loads(row['body']) if row else {}, 'revision': row['revision'] if row else 0}


class RecordUpdate(BaseModel):
    data: dict[str, str]
    revision: int = Field(ge=0)


@router.put('/records')
def save_records(req: RecordUpdate, who=Depends(student)):
    body = json.dumps(req.data, ensure_ascii=False)
    if len(body.encode()) > 10_000_000:
        raise HTTPException(413, '学习记录超过10MB，请先导出并清理过大的图片会话')
    with connect() as db:
        db.execute('BEGIN IMMEDIATE')
        row = db.execute('SELECT revision FROM records WHERE student=?', (who,)).fetchone()
        if (row['revision'] if row else 0) != req.revision:
            raise HTTPException(409, '其他窗口已更新记录，请导出当前记录备份后重新登录，避免覆盖')
        db.execute('INSERT OR REPLACE INTO records VALUES (?,?,?)', (who, body, req.revision + 1))
    return {'revision': req.revision + 1}


class Feedback(BaseModel):
    content: str = Field(min_length=1, max_length=4000)
    context: str = Field(default='', max_length=200)


@router.post('/feedback')
def submit_feedback(req: Feedback, who=Depends(student)):
    body = req.content.strip()
    if not body:
        raise HTTPException(400, '意见内容不能为空')
    with connect() as db:
        db.execute(
            'INSERT INTO feedback (student, body, context, ts) VALUES (?,?,?,?)',
            (who, body, req.context.strip()[:200], time.time()),
        )
    return {'ok': True}


@router.get('/feedback')
def list_feedback(who=Depends(student)):
    with connect() as db:
        rows = db.execute(
            'SELECT id, student, body, context, ts FROM feedback WHERE student=? ORDER BY id DESC LIMIT 300',
            (who,),
        ).fetchall()
    return {
        'items': [
            {
                'id': r['id'],
                'studentId': r['student'],
                'content': r['body'],
                'context': r['context'],
                'time': r['ts'],
            }
            for r in rows
        ]
    }


# ── 管理端（只读统计 + 展示页）─────────────────────────────────
# 口令来源：环境变量 ADMIN_TOKEN > private/admin_token.txt（在 .gitignore 内）。
# 两者都没有则管理端整体关闭（一律 403）。请求侧可用 X-Admin-Token 头或 ?token= 参数。
TOKEN_FILE = DB.parent / 'admin_token.txt'


def admin_token():
    expected = os.environ.get('ADMIN_TOKEN', '')
    if expected:
        return expected
    try:
        return TOKEN_FILE.read_text(encoding='utf-8').strip()
    except OSError:
        return ''


def admin(x_admin_token: str = Header(default=''), token: str = ''):
    expected = admin_token()
    if not expected or not hmac.compare_digest(x_admin_token or token, expected):
        raise HTTPException(403, '需要管理员令牌（ADMIN_TOKEN/admin_token.txt 未配置或令牌不符）')


@router.get('/admin', response_class=HTMLResponse)
def admin_page():
    """管理页本体不含数据（数据走 /admin/stats），所以页面本身不鉴权，口令在页面上输入。"""
    return HTMLResponse((Path(__file__).parent / 'admin_page.html').read_text(encoding='utf-8'))


@router.get('/admin/stats')
def admin_stats(_=Depends(admin)):
    """教师侧只读统计：注册账号、活跃会话、学习记录与全部意见反馈。"""
    with connect() as db:
        users = [r['id'] for r in db.execute('SELECT id FROM users ORDER BY id')]
        sessions = db.execute(
            'SELECT COUNT(*) c FROM sessions WHERE expires>?', (time.time(),)
        ).fetchone()['c']
        records_count = db.execute('SELECT COUNT(*) c FROM records').fetchone()['c']
        rows = db.execute(
            'SELECT id, student, body, context, ts FROM feedback ORDER BY id DESC LIMIT 300'
        ).fetchall()
    return {
        'userCount': len(users),
        'users': users,
        'activeSessions': sessions,
        'recordsCount': records_count,
        'feedbackCount': len(rows),
        'feedback': [
            {
                'id': r['id'],
                'studentId': r['student'],
                'content': r['body'],
                'context': r['context'],
                'time': r['ts'],
            }
            for r in rows
        ],
    }
