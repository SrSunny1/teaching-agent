def categories() -> list[str]:
    """库里实际出现的分类（保持稳定顺序）。"""
    seen = list(dict.fromkeys(e["category"] for e in ENTRIES))
    return seen


def match_entries(topic: str, category: str | None = None) -> list[dict]:
    """按主题/分类挑错题。topic 做中文 2-gram 重叠匹配，避免单字误命中。"""
    key = re.sub(r"\s+", "", topic or "")
    grams = [key[i : i + 2] for i in range(max(len(key) - 1, 0))] or ([key] if key else [])
    out = []
    for e in ENTRIES:
        if category and e["category"] != category:
            continue
        if not key:
            out.append(e)
            continue
        hay = f'{e["category"]} {e["question"]} {e["knowledgePoint"]} {e["knowledgeRefs"][0] if e["knowledgeRefs"] else ""}'
        if key in hay or (grams and sum(1 for g in grams if g in hay) >= max(1, len(grams) // 2)):
            out.append(e)
    return out
