async def _run(args: dict) -> ToolResult:
    module = args.get("module")
    module = str(module) if module else None

    total = sum(len(v) for v in RULES.values())
    lines = ["按类别聚合的实验室安全规范（跨实验汇总）："]

    for category, items in RULES.items():
        lines.append(f"\n## {category}（{len(items)} 条）")
        for rule, ref in items:
            lines.append(f"- {rule}\n  └ {ref}")

    if module:
        lines.append(f"\n（学生指定关注模块：{module}）")

    lines.append(
        f"\n共 {total} 条。这些规范原本散落在各实验的「注意事项」里，"
        "本清单按劳育模块一的口径做了归类。"
    )

    return ToolResult(
        summary=f"{total} 条 · 分 {len(RULES)} 类",
        detail="\n".join(lines),
    )


